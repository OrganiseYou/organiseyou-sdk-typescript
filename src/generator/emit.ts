import {
  compare,
  type EndpointModel,
  type FieldModel,
  type Model,
  type ObjectModel,
} from './document.js';
import { NameAllocator, propertyKey, quote, typeIdentifier } from './names.js';

/** The name of the manifest in the output folder. */
export const MANIFEST_NAME = '.organiseyou-generated.json';

/** Every generated source file starts with this, then the generator's version. */
export const GENERATED_PREFIX = '// Generated by organiseyou ';

export interface EmitOptions {
  /** The version of the generator, written in the first line of every file and in the manifest. */
  version: string;
  /** The package the generated code imports its types from. */
  sdkPackage: string;
}

/** The files of the output folder, by name, in the order they are written: the manifest is last. */
export type Output = Map<string, string>;

function header(version: string): string {
  return `${GENERATED_PREFIX}${version}, do not edit.\n`;
}

/** The names the generated code gives to what the document describes. */
interface Names {
  /** The component name to the name of its interface. */
  types: Map<string, string>;
  /** The endpoint name to the name of its class. */
  classes: Map<string, string>;
}

function allocateNames(model: Model): Names {
  const allocator = new NameAllocator();
  const types = new Map<string, string>();
  for (const component of model.objects.keys()) {
    types.set(component, allocator.take(typeIdentifier(component)));
  }
  const classes = new Map<string, string>();
  for (const endpoint of model.endpoints) {
    // The class follows the name of the record's interface, so the two read as a pair
    const base =
      endpoint.record === undefined
        ? typeIdentifier(endpoint.name)
        : (types.get(endpoint.record) ?? typeIdentifier(endpoint.name));
    classes.set(endpoint.name, allocator.take(`${base}Endpoint`));
  }
  return { types, classes };
}

/** Builds every file of the output from the model. The same model always gives the same text. */
export function emit(model: Model, options: EmitOptions): Output {
  const names = allocateNames(model);
  const output: Output = new Map();
  output.set('models.ts', emitModels(model, names, options));
  output.set('endpoints.ts', emitEndpoints(model, names, options));
  output.set('index.ts', emitIndex(model, names, options));
  output.set(MANIFEST_NAME, emitManifest(model, [...output.keys()].sort(compare), options));
  return output;
}

function emitModels(model: Model, names: Names, options: EmitOptions): string {
  const lines = [header(options.version).trimEnd(), ''];
  lines.push('/** Any value JSON can hold. */');
  lines.push(
    'export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };',
  );
  for (const [component, object] of model.objects) {
    lines.push('', ...emitObject(names.types.get(component) ?? component, object));
  }
  return `${lines.join('\n')}\n`;
}

function emitObject(name: string, object: ObjectModel): string[] {
  if (object.open) return [`export interface ${name} {`, '  [key: string]: JsonValue;', '}'];
  const lines = [`export interface ${name} {`];
  for (const field of object.fields) lines.push(`  ${emitField(field)}`);
  lines.push('}');
  return lines;
}

function emitField(field: FieldModel): string {
  const type = field.nullable ? `${field.type} | null` : field.type;
  return `${field.readOnly ? 'readonly ' : ''}${propertyKey(field.key)}${field.required ? '' : '?'}: ${type};`;
}

function emitEndpoints(model: Model, names: Names, options: EmitOptions): string {
  const lines = [
    header(options.version).trimEnd(),
    `import type * as oy from ${quote(options.sdkPackage)};`,
    "import type * as m from './models.js';",
  ];
  for (const endpoint of model.endpoints) {
    lines.push('', ...emitEndpoint(endpoint, names));
  }
  return `${lines.join('\n')}\n`;
}

function emitEndpoint(endpoint: EndpointModel, names: Names): string[] {
  const className = names.classes.get(endpoint.name) ?? endpoint.name;
  const typeOf = (component: string | undefined, fallback: string): string => {
    const name = component === undefined ? undefined : names.types.get(component);
    return name === undefined ? fallback : `m.${name}`;
  };
  const record = typeOf(endpoint.record, 'oy.RecordData');
  const input = typeOf(endpoint.input, 'oy.RecordValues');
  const update = typeOf(endpoint.updateInput, 'oy.RecordValues');

  const lines = [
    '/** The records of one endpoint, with only the operations the organization has switched on. */',
    `export class ${className} {`,
    '  readonly #records: oy.Records;',
    '',
    '  constructor(client: oy.OrganiseYou) {',
    `    this.#records = client.records(${quote(endpoint.name)});`,
    '  }',
  ];
  const method = (text: string[]): void => {
    lines.push('', ...text);
  };
  if (endpoint.list) {
    method([
      `  list(options?: oy.ListOptions): Promise<oy.Page<${record}>> {`,
      `    return this.#records.list(options) as unknown as Promise<oy.Page<${record}>>;`,
      '  }',
      '',
      `  all(options?: oy.AllOptions): AsyncGenerator<${record}, void, undefined> {`,
      `    return this.#records.all(options) as unknown as AsyncGenerator<${record}, void, undefined>;`,
      '  }',
    ]);
  }
  if (endpoint.get) {
    method([
      `  get(id: string, options?: oy.RequestOptions): Promise<${record}> {`,
      `    return this.#records.get(id, options) as unknown as Promise<${record}>;`,
      '  }',
    ]);
  }
  if (endpoint.create) {
    method([
      `  create(values: ${input}, options?: oy.RequestOptions): Promise<${record}> {`,
      `    return this.#records.create({ ...values }, options) as unknown as Promise<${record}>;`,
      '  }',
    ]);
  }
  if (endpoint.update) {
    method([
      `  update(id: string, values: ${update}, options?: oy.RequestOptions): Promise<${record}> {`,
      `    return this.#records.update(id, { ...values }, options) as unknown as Promise<${record}>;`,
      '  }',
    ]);
  }
  if (endpoint.delete) {
    method([
      '  delete(id: string, options?: oy.RequestOptions): Promise<void> {',
      '    return this.#records.delete(id, options);',
      '  }',
    ]);
  }
  lines.push('}');
  return lines;
}

function emitIndex(model: Model, names: Names, options: EmitOptions): string {
  const classes = model.endpoints.map(
    (endpoint) => names.classes.get(endpoint.name) ?? endpoint.name,
  );
  const lines = [
    header(options.version).trimEnd(),
    `import type * as oy from ${quote(options.sdkPackage)};`,
    `import { ${[...classes].sort(compare).join(', ')} } from './endpoints.js';`,
    '',
    "export type * from './endpoints.js';",
    "export type * from './models.js';",
    '',
    '/** The endpoints of the organization, by name. */',
    'export interface Api {',
  ];
  for (const endpoint of model.endpoints) {
    lines.push(
      `  readonly ${propertyKey(endpoint.name)}: ${names.classes.get(endpoint.name) ?? endpoint.name};`,
    );
  }
  lines.push('}', '', '/** The typed API of one organization, over a client you made. */');
  lines.push('export function createApi(client: oy.OrganiseYou): Api {', '  return {');
  for (const endpoint of model.endpoints) {
    lines.push(
      `    ${propertyKey(endpoint.name)}: new ${names.classes.get(endpoint.name) ?? endpoint.name}(client),`,
    );
  }
  lines.push('  };', '}');
  return `${lines.join('\n')}\n`;
}

function emitManifest(model: Model, files: string[], options: EmitOptions): string {
  const manifest = {
    generator: { name: 'organiseyou', version: options.version },
    document: {
      sha256: model.sha256,
      ...(model.revision === undefined ? {} : { revision: model.revision }),
    },
    files,
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}
